"""Poll the plan2 design-draft batches, write each draft to docs/handoff/plan2/drafts/<batch>/<id>.md and the README index.

    python tools/batch/ingest_drafts.py batches/plan2/batch_ids.json            # wait, fetch, write
    python tools/batch/ingest_drafts.py batches/plan2/batch_ids.json --no-wait  # only what has ended

Credentials: ANTHROPIC_API_KEY (or the Windows user variable of that name); never printed.
Cost (Sonnet 5.5 batch, -50 %): input $1.00, cache write $1.25, cache read $0.10, output $5.00 per MTok.
Written as a file on purpose: never run Python from stdin on this machine.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

import anthropic

ROOT = Path(__file__).resolve().parent.parent.parent
DIRS = {"enemy": "enemies", "corp": "bosses", "hq": "hq", "node": "nodes", "raid": "raids", "event": "events"}
P_IN, P_CW, P_CR, P_OUT = 1.0, 1.25, 0.10, 5.0


def api_key() -> str:
    k = os.environ.get("ANTHROPIC_API_KEY")
    if k:
        return k
    import winreg

    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as h:
        return winreg.QueryValueEx(h, "ANTHROPIC_API_KEY")[0]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("ids")
    ap.add_argument("--no-wait", action="store_true")
    ap.add_argument("--poll", type=int, default=60)
    args = ap.parse_args()
    client = anthropic.Anthropic(api_key=api_key())
    ids = json.loads(Path(args.ids).read_text(encoding="utf-8"))
    out_root = ROOT / "docs/handoff/plan2/drafts"
    out_root.mkdir(parents=True, exist_ok=True)
    rows = []
    totals = [0, 0, 0, 0]
    for name, bid in ids.items():
        while True:
            b = client.messages.batches.retrieve(bid)
            if b.processing_status == "ended" or args.no_wait:
                break
            print(f"{name}: {b.processing_status} {b.request_counts.processing} processing", flush=True)
            time.sleep(args.poll)
        if b.processing_status != "ended":
            rows.append((name, "-", "pending", 0, 0.0))
            continue
        for r in client.messages.batches.results(bid):
            cid = r.custom_id
            kind, _, item = cid.partition("__")
            d = out_root / DIRS[kind]
            d.mkdir(parents=True, exist_ok=True)
            rtype = r.result.type
            if rtype != "succeeded":
                rows.append((DIRS[kind], item, rtype, 0, 0.0))
                continue
            m = r.result.message
            text = "".join(bl.text for bl in m.content if bl.type == "text").strip()
            u = m.usage
            cw = u.cache_creation_input_tokens or 0
            cr = u.cache_read_input_tokens or 0
            tin = u.input_tokens
            tout = u.output_tokens
            cost = (tin * P_IN + cw * P_CW + cr * P_CR + tout * P_OUT) / 1e6
            for i, v in enumerate((tin, cw, cr, tout)):
                totals[i] += v
            status = "ok" if m.stop_reason == "end_turn" else f"TRUNCATED ({m.stop_reason})"
            head = (
                f"<!-- draft via Message Batches API, {m.model}, batch {bid}, custom_id {cid}; status {status}; "
                f"tokens in {tin} cache-write {cw} cache-read {cr} out {tout}; cost ${cost:.3f}. "
                f"A DESIGN DRAFT for the designer's review: nothing here is built. -->\n\n"
            )
            (d / f"{item}.md").write_text(head + text + "\n", encoding="utf-8", newline="\n")
            rows.append((DIRS[kind], item, status, tin + cw + cr + tout, cost))
    # Rebuild the index from every draft header, so a retry run merges with the earlier ones.
    import re

    hdr = re.compile(r"status (.*?); tokens in (\d+) cache-write (\d+) cache-read (\d+) out (\d+); cost \$(\d+\.\d+)")
    rows = []
    totals = [0, 0, 0, 0]
    extra_cost = 0.0
    for sub in sorted(set(DIRS.values())):
        for f in sorted((out_root / sub).glob("*.md")):
            m = hdr.search(f.read_text(encoding="utf-8")[:900])
            if not m:
                continue
            tin, cw, cr, tout = (int(m.group(i)) for i in (2, 3, 4, 5))
            for i, v in enumerate((tin, cw, cr, tout)):
                totals[i] += v
            rows.append((sub, f.stem, m.group(1), tin + cw + cr + tout, float(m.group(6))))
    rows.sort()
    total_cost = sum(r[4] for r in rows) + extra_cost
    lines = [
        "# Plan 2 design drafts (Message Batches, Sonnet 5.5)",
        "",
        "Drafts for the designer's review. Nothing here is built; names are placeholders. Rules: `../CONTENT_DESIGN_V2.md`; rulings: DECISIONS 2026-10-16.",
        "Generated by `tools/batch/build_design_drafts.py` (spec) and `tools/batch/ingest_drafts.py` (this index).",
        "",
        f"Totals: input {totals[0]:,} (uncached) + {totals[1]:,} cache-write + {totals[2]:,} cache-read, output {totals[3]:,} tokens; cost about ${total_cost:.2f} (batch price).",
        "",
        "| batch | item | status | tokens | cost |",
        "|---|---|---|---|---|",
    ]
    for b, item, st, tok, c in rows:
        link = f"[{item}]({b}/{item}.md)" if st in ("ok",) or st.startswith("TRUNC") else item
        lines.append(f"| {b} | {link} | {st} | {tok:,} | ${c:.3f} |")
    (out_root / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} rows; total ${total_cost:.2f}; tokens {totals}")
    bad = [r for r in rows if r[2] != "ok"]
    print("not ok:", bad)
    return 0


if __name__ == "__main__":
    sys.exit(main())
