"""skin_tables_r2 (round 2, 2026-11-04): run the published port/src/skin_tables.py on the round-2 generator.

Round 1 ran skin_tables.py with rb_patch._skins() as the only skin install.  On the round-2 board, lw_render also installs
rb4_patch, whose _solace() re-inks every Solace piece in the teal family (C16) and gives the rope its long lay (C18).  This wrapper
installs that one rb4 step right after rb_patch._skins() (the same order lw_render uses), then runs skin_tables.main unchanged, and
adds the rb4_patch md5 and a round-2 note to the output.  Nothing in corp/src or port/src is written (no bytecode).
usage: python skin_tables_r2.py <out_json>"""
import sys, os, json, hashlib, importlib.util
sys.dont_write_bytecode = True
PORT_SRC = 'D:/rc_art/art-pass/docs/concepts/combat_redesign/locked/port/src/skin_tables.py'
CORP = 'D:/rc_scratch/combat_redesign/locked/corp/src'

spec = importlib.util.spec_from_file_location('skin_tables', PORT_SRC)
ST = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ST)          # imports corp/src (read-only) as the round-1 script does
sys.path.insert(0, CORP)
import rb4_patch as RB4               # noqa: E402
import rb5_patch as RB5               # noqa: E402

_orig_skins = ST.RBP._skins


def _skins_r2():
    out = _orig_skins()
    RB4._solace(None)                 # rb4_patch.install order: ... _tickets(SKIN), _solace(SKIN) (SKIN is unused by _solace)
    RB5.solace_ticket()               # 2026-11-04 round 2 gate-1 fix: the Solace ticket method is the one the board draws (teal edge, W4 crest)
    return out


ST.RBP._skins = _skins_r2
out = sys.argv[1]
ST.main(out)
res = json.load(open(out, encoding='utf-8'))
res['version'] = 'port-3'
res['sources']['rb4_patch.py'] = hashlib.md5(open(RB4.__file__, 'rb').read()).hexdigest()
res['sources']['rb5_patch.py'] = hashlib.md5(open(RB5.__file__, 'rb').read()).hexdigest()
T = ST.T
res['targets_r2'] = dict(
    e_line_L=T.E_LINE_L, struct_cap_L=T.STRUCT_CAP_L, struct_class_L=T.STRUCT_CLASS_L, unclassed_L=T.UNCLASSED_L, unclassed_r=T.UNCLASSED_R,
    drawn_de=T.DRAWN_DE, pen_wax_px=list(T.PEN_WAX_PX), pen_ink_px=list(T.PEN_INK_PX), pen_grain_L_std=T.PEN_GRAIN_L_STD,
    ticket_edge_vals=list(T.TICKET_EDGE_VALS), ticket_step_L=T.TICKET_STEP_L, hot_core_px_min=T.HOT_CORE_PX_MIN,
    hot_core_ratio_min=T.HOT_CORE_RATIO_MIN, rim_de_min=T.RIM_DE_MIN, hub_hp_green=ST.hexs(T.HUB_HP_GREEN))
res['skin_inks_retired'] = {k: {n: ST.tok(c) for n, c in v.items()} for k, v in T.SKIN_INKS_RETIRED.items()}
res['round2'] = ('2026-11-04 round 2: generated by round2/docs/port/skin_tables_r2.py, which runs port/src/skin_tables.py with '
                 'rb4_patch._solace installed after rb_patch._skins (C16 teal Solace inks, C18 long-lay rope), as lw_render installs it '
                 'for the round-2 plates in final/')
json.dump(res, open(out, 'w', encoding='utf-8'), indent=1)
print('wrote', out, 'solace inks', res['skins']['solace']['inks'], 'pal primary', res['skins']['solace']['pal'].get('primary'))
