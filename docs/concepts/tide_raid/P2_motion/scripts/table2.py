"""Write TIMING_TABLE.md and tide_look_motion.tres.txt from spec.py."""
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, 'D:/rc_art/art-pass/docs/concepts/tide_raid/P2_motion/scripts')
sys.path.append('D:/rc_art/art-pass/docs/concepts/tide_raid/P1_motion/scripts')
import spec2 as SP
from tl import EASE_GODOT

OUT = 'D:/rc_art/art-pass/docs/concepts/tide_raid/P2_motion/'


def ms(f):
    return int(round(f * 1000 / 30.0))


def rmode(t):
    s = t.lower()
    if s.startswith('removed') or 'no shake' in s or s.startswith('no bits') or 'dropped' in s and 'ring' not in s:
        return 'REMOVE'
    if 'cross-fade' in s or 'cross fade' in s:
        return 'CROSSFADE'
    if s.startswith('identical') or s.startswith('same') or s.startswith('keep'):
        return 'KEEP'
    if 'fade' in s:
        return 'FADE'
    if s.startswith('cut') or s.startswith('skipped') or s.startswith('no '):
        return 'CUT'
    return 'SEE_TABLE'


def main():
    md = ['# Tide raid motion: timing table for build (30 fps)', '',
          'Source of truth: `scripts/spec.py` (this file is generated by `scripts/table.py`). Every value below is a `tide_look.tres`',
          'property (no magic numbers in code). `_f` = frames at `fps` (30). Seconds are derived: `_f / fps`.', '',
          '## Global motion tuning', '', '| key | value | meaning |', '|---|---|---|']
    for k, v, n in SP.GLOBAL:
        md.append('| `%s` | %s | %s |' % (k, v, n))
    md += ['', '## Skip / fast-forward codes', '',
           '- `SNAP`: the beat jumps to its end state in `skip_snap_f` (2) frames when the player skips (one input).',
           '- `FF`: holding skip plays the beat at `skip_speed` (4x); holds inside it are floored at `skip_hold_min_f` (3).',
           '- `HOLD`: a hold only a player action ends (telegraph, read hold); `HOLD min N` = it may be fast-forwarded down to N frames.',
           '- `NONE`: input-bound or already instant, never skipped.', '',
           '## Reduce-motion codes (also in the table text)', '',
           '- `KEEP` identical (holds are always kept). `CROSSFADE` replace by a cross-fade of `reduce_grade_cross_fade_f`. `FADE` replace by a',
           '  `reduce_fade_f` fade. `CUT` skipped / state cut. `REMOVE` the effect is not shown (shake, jitter, tear, fringe, strobe).',
           '  Every flash becomes ONE `reduce_flash_f` brightness step capped at `reduce_flash_cap_alpha`.', '']
    tres = ['# tide_look.tres: motion block (paste into the TideLook resource; frames at fps=30)', '']
    for k, v, n in SP.GLOBAL:
        val = ('true' if v is True else 'false' if v is False else v)
        tres.append('%s = %s  # %s' % (k, val, n))
    tres.append('')
    for bd in SP.BOARDS:
        md += ['## Board %s: %s' % (bd['id'], bd['title']), '',
               'Total %d f (%.2f s); interactive from f%d. Means: %s' % (bd['total'], bd['total'] / 30.0, bd['ready'], bd['means']), '',
               '| key | start f | dur f | dur ms | ease | Godot tween | skip | reduce | reduce-motion rule | reference number beaten / borrowed |',
               '|---|---:|---:|---:|---|---|---|---|---|---|']
        tres.append('# --- board %s %s' % (bd['id'], bd['title']))
        for b in bd['beats']:
            key, label, f0, f1, ease, means, sound, cite, skip, red = b
            md.append('| `%s` | %d | %d | %d | %s | %s | %s | %s | %s | %s |' % (key, f0, f1 - f0, ms(f1 - f0), ease, EASE_GODOT[ease], skip, rmode(red), red, cite))
            tres.append('%s_start_f = %d' % (key, f0))
            tres.append('%s_f = %d' % (key, f1 - f0))
            tres.append('%s_ease = &"%s"' % (key, ease))
            tres.append('%s_skip = &"%s"' % (key, skip.replace(' ', '_')))
            tres.append('%s_reduce = &"%s"' % (key, rmode(red)))
        md.append('')
        if bd.get('extras'):
            md += ['Extra values:', '']
            for k, v, n in bd['extras']:
                md.append('- `%s` = %s: %s' % (k, v, n))
                tres.append('%s = %s' % (k, v))
            md.append('')
        tres.append('')
    open(OUT + 'TIMING_TABLE.md', 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    open(OUT + 'tide_look_motion.tres.txt', 'w', encoding='utf-8').write('\n'.join(tres) + '\n')
    print('ok')


main()
