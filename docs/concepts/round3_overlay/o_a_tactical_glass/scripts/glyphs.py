"""Single-stroke hand-lettering skeletons for the grease-pencil layer.

Units: cap height = 1, y grows downward, x from 0 to the glyph width.
Each glyph is (width, [stroke, stroke, ...]); strokes are listed in writing order,
so the lifecycle 'write' animation can play them stroke by stroke.
"""
import math


def arc(cx, cy, rx, ry, a0, a1, n=None):
    """Points on an ellipse arc from a0 to a1 (degrees, either direction)."""
    if n is None:
        n = max(6, int(abs(a1 - a0) / 9))
    pts = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts


